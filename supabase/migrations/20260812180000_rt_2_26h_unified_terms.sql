create or replace function private.get_my_mesa_os_terms_state()
returns table (document_version_id uuid, title text, body_markdown text, content_sha256 text, latest_event public.legal_document_acceptance_event, automation_enabled boolean)
language sql stable security definer set search_path = '' as $$
  with member as (
    select organization_id from public.memberships where identity_id = (select auth.uid()) and status = 'active'
  ), document as (
    select id, title, body_markdown, content_sha256 from public.legal_document_versions where code = 'mesa_os_terms' and status = 'published'
  )
  select d.id, d.title, d.body_markdown, d.content_sha256,
    (select a.event from public.legal_document_acceptances a, member m where a.document_version_id = d.id and a.organization_id = m.organization_id and a.identity_id = (select auth.uid()) order by a.created_at desc, a.id desc limit 1),
    coalesce((select p.automation_enabled from public.organization_tutoria_context_policies p, member m where p.organization_id = m.organization_id and p.legal_document_version_id = d.id), false)
  from document d where exists (select 1 from member)
$$;

create or replace function private.accept_my_mesa_os_terms(target_document_version_id uuid)
returns uuid language plpgsql security definer set search_path = '' as $$
declare actor_id uuid := (select auth.uid()); target_organization_id uuid; receipt_id uuid;
begin
  if actor_id is null then raise exception 'authentication required' using errcode = '42501'; end if;
  select organization_id into target_organization_id from public.memberships where identity_id = actor_id and status = 'active';
  if target_organization_id is null or not exists (select 1 from public.legal_document_versions where id = target_document_version_id and code = 'mesa_os_terms' and status = 'published') then raise exception 'active membership and current terms required' using errcode = '42501'; end if;
  receipt_id := private.accept_legal_document_version(target_document_version_id);
  if exists (select 1 from public.memberships where identity_id = actor_id and organization_id = target_organization_id and role = 'owner' and status = 'active') then
    insert into public.organization_tutoria_context_policies (organization_id, automation_enabled, legal_document_version_id, enabled_at, enabled_by)
    values (target_organization_id, true, target_document_version_id, now(), actor_id)
    on conflict (organization_id) do update set automation_enabled = true, legal_document_version_id = excluded.legal_document_version_id, enabled_at = excluded.enabled_at, enabled_by = excluded.enabled_by, updated_at = now();
  end if;
  return receipt_id;
end;
$$;

create or replace function private.withdraw_my_mesa_os_tutoria_context(target_document_version_id uuid)
returns uuid language plpgsql security definer set search_path = '' as $$
declare actor_id uuid := (select auth.uid()); target_organization_id uuid; document_hash text; receipt_id uuid;
begin
  if actor_id is null then raise exception 'authentication required' using errcode = '42501'; end if;
  select organization_id into target_organization_id from public.memberships where identity_id = actor_id and status = 'active';
  select content_sha256 into document_hash from public.legal_document_versions where id = target_document_version_id and code = 'mesa_os_terms' and status = 'published';
  if target_organization_id is null or document_hash is null then raise exception 'active membership and current terms required' using errcode = '42501'; end if;
  insert into public.legal_document_acceptances (document_version_id, organization_id, identity_id, event, document_sha256) values (target_document_version_id, target_organization_id, actor_id, 'withdrawn', document_hash) returning id into receipt_id;
  return receipt_id;
end;
$$;

